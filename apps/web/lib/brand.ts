function withArrays(colors: ThemeColors) {
    return {
        ...colors,
        /** Every colour token, in `colorTokenNames` order. */
        colors: colorTokenNames.map((name) => colors[name]),
        /** Chart series order: primary, accent, success, warning, destructive. */
        chart: [
            colors['chart-1'],
            colors['chart-2'],
            colors['chart-3'],
            colors['chart-4'],
            colors['chart-5'],
        ],
    } as const
}

